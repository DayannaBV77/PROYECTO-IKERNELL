CREATE TABLE rol (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre_rol VARCHAR(50) NOT NULL,
    CONSTRAINT pk_rol PRIMARY KEY (id),
    CONSTRAINT uq_rol_nombre UNIQUE (nombre_rol)
);

INSERT INTO rol (nombre_rol) VALUES
    ('Coordinador'),
    ('Líder'),
    ('Desarrollador');

DROP INDEX IF EXISTS uq_asignacion_trabajador_proyecto_rol_activa;

ALTER TABLE asignacion RENAME TO rol_trabajador;
ALTER TABLE rol_trabajador ADD COLUMN rol_id BIGINT;

UPDATE rol_trabajador
SET rol_id = (
    SELECT r.id
    FROM rol r
    WHERE r.nombre_rol = CASE rol_trabajador.rol_en_proyecto
        WHEN 'LIDER' THEN 'Líder'
        WHEN 'DESARROLLADOR' THEN 'Desarrollador'
    END
);

ALTER TABLE rol_trabajador ALTER COLUMN rol_id SET NOT NULL;
ALTER TABLE rol_trabajador
    ADD CONSTRAINT fk_rol_trabajador_rol FOREIGN KEY (rol_id) REFERENCES rol (id);
ALTER TABLE rol_trabajador DROP CONSTRAINT ck_asignacion_rol;
ALTER TABLE rol_trabajador DROP COLUMN rol_en_proyecto;

CREATE INDEX ix_rol_trabajador_trabajador ON rol_trabajador (trabajador_id, activa);
CREATE INDEX ix_rol_trabajador_proyecto ON rol_trabajador (proyecto_id, activa);
