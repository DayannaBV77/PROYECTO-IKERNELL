-- -----------------------------------------------------------------------------
-- recurso_interno
--
-- Tabla SEPARADA de contenido_publico aunque el patron sea el mismo. El motivo
-- no es de estilo: contenido_publico se sirve por /api/publico sin
-- autenticacion, y meter aqui los recursos internos dejaria a un descuido de
-- una linea la posibilidad de exponerlos a cualquier visitante. RF-029 y RF-030
-- los reservan a los trabajadores autenticados, y HU-01 C05 prohibe que el
-- interesado llegue a ellos.
--
-- Uso de las columnas segun el tipo:
--   PROGRAMA : titulo + descripcion + enlace (al recurso) + version
--   TUTORIAL : titulo + descripcion + contenido (el tutorial) + enlace opcional
-- -----------------------------------------------------------------------------
CREATE TABLE recurso_interno (
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    tipo        VARCHAR(20)   NOT NULL,
    titulo      VARCHAR(250)  NOT NULL,
    descripcion VARCHAR(2000),

    -- PENDIENTE D-27: RF-029 deja sin definir "la forma de busqueda, descarga,
    -- versiones y permisos" y RF-030 "la administracion, clasificacion, formato
    -- y actualizacion". categoria y version existen porque HU-21 C05 contempla
    -- filtros y RF-029 menciona versiones, pero su uso debe acordarse.
    categoria   VARCHAR(100),
    version     VARCHAR(50),

    contenido   VARCHAR(16000),
    enlace      VARCHAR(500),
    orden       INT,
    publicada   BOOLEAN       NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_recurso_interno PRIMARY KEY (id),
    CONSTRAINT ck_recurso_interno_tipo CHECK (tipo IN ('PROGRAMA', 'TUTORIAL'))
);

CREATE INDEX ix_recurso_interno_tipo ON recurso_interno (tipo, publicada);
