-- Trazabilidad de cada columna:
--   CONFIRMADO : literal en el Caso de Estudio ADSI 2017, el Catalogo RF o las HU
--   DERIVADO   : consecuencia necesaria de una regla confirmada
--   PROPUESTA  : diseno pendiente de validacion con la empresa
--
-- El esquema NO es definitivo. Las restricciones marcadas como pendientes se
-- agregaran en migraciones posteriores cuando la empresa defina los dominios.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- trabajador: perfil personal y profesional.
-- Por decision D-01 este perfil NO contiene credenciales de acceso; la
-- identificacion se conserva como dato personal, no como credencial.
-- -----------------------------------------------------------------------------
CREATE TABLE trabajador (
    id                      BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    identificacion          VARCHAR(20)  NOT NULL,  -- CONFIRMADO: unica (RN-01)
    nombre                  VARCHAR(100) NOT NULL,  -- CONFIRMADO
    apellido                VARCHAR(100) NOT NULL,  -- CONFIRMADO
    fecha_nacimiento        DATE         NOT NULL,  -- CONFIRMADO
    direccion               VARCHAR(200) NOT NULL,  -- CONFIRMADO
    profesion               VARCHAR(100) NOT NULL,  -- CONFIRMADO; texto libre (D-17 abierto)
    especialidad_desarrollo VARCHAR(100) NOT NULL,  -- CONFIRMADO; texto libre (D-17 abierto)
    tipo_trabajador         VARCHAR(15)  NOT NULL,  -- CONFIRMADO: Caso de Estudio p.2
    estado                  VARCHAR(15)  NOT NULL DEFAULT 'HABILITADO', -- CONFIRMADO: RN-02/RN-03
    foto_ruta               VARCHAR(500),           -- CONFIRMADO; nullable por HU-04 C05
    foto_content_type       VARCHAR(100),           -- DERIVADO: validacion de RF-002
    foto_tamano_bytes       BIGINT,                 -- DERIVADO: validacion de RF-002

    CONSTRAINT pk_trabajador PRIMARY KEY (id),
    CONSTRAINT uk_trabajador_identificacion UNIQUE (identificacion),
    CONSTRAINT ck_trabajador_tipo CHECK (tipo_trabajador IN ('COORDINADOR', 'LIDER', 'DESARROLLADOR')),
    CONSTRAINT ck_trabajador_estado CHECK (estado IN ('HABILITADO', 'INHABILITADO'))
);

-- Criterios de busqueda declarados en RF-004 / HU-05 C01.
CREATE INDEX ix_trabajador_nombre       ON trabajador (nombre);
CREATE INDEX ix_trabajador_apellido     ON trabajador (apellido);
CREATE INDEX ix_trabajador_profesion    ON trabajador (profesion);
CREATE INDEX ix_trabajador_especialidad ON trabajador (especialidad_desarrollo);
CREATE INDEX ix_trabajador_tipo         ON trabajador (tipo_trabajador);

-- -----------------------------------------------------------------------------
-- cuenta_acceso: autenticacion, separada del perfil (decision D-01).
-- Relacion 1 a 0..1: RF-001 registra el perfil sin credenciales, por lo que un
-- trabajador puede existir sin cuenta (HU-04 T1 deja el punto abierto).
--
-- PROPUESTA pendiente de validacion por la empresa:
--   - el identificador de acceso es el correo corporativo
--   - D-19: queda por confirmar si es el mismo correo del servicio de RF-031
--
-- Sin columna de estado propia: el inicio de sesion valida trabajador.estado,
-- para que RN-03 ("el inhabilitado no inicia sesion") viva en un solo lugar.
-- -----------------------------------------------------------------------------
CREATE TABLE cuenta_acceso (
    id                 BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    trabajador_id      BIGINT       NOT NULL,
    correo_corporativo VARCHAR(150) NOT NULL,  -- PROPUESTA: D-01
    password_hash      VARCHAR(100) NOT NULL,  -- CONFIRMADO por RNF-001 (hash seguro)
    ultimo_acceso_en   TIMESTAMP,              -- PROPUESTA

    CONSTRAINT pk_cuenta_acceso PRIMARY KEY (id),
    CONSTRAINT uk_cuenta_acceso_trabajador UNIQUE (trabajador_id),
    CONSTRAINT uk_cuenta_acceso_correo UNIQUE (correo_corporativo),
    CONSTRAINT fk_cuenta_acceso_trabajador FOREIGN KEY (trabajador_id)
        REFERENCES trabajador (id)
);
