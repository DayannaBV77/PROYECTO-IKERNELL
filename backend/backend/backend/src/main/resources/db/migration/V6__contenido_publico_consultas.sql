-- -----------------------------------------------------------------------------
-- contenido_publico
--
-- UNA tabla para las seis secciones que enumera HU-01 C01, en lugar de seis
-- tablas distintas. El motivo: ningun RF define los atributos de ninguna de
-- esas secciones, de modo que inventar seis esquemas distintos seria inventar
-- mas estructura que la estrictamente necesaria. Las seis comparten el mismo
-- ciclo de vida -publicar, despublicar, ordenar- y la misma forma: una etiqueta
-- y un contenido.
--
-- Como se usan las columnas segun el tipo:
--   LINEAMIENTO          : titulo + cuerpo
--   PORTAFOLIO_SERVICIO  : titulo + cuerpo
--   NOTICIA              : titulo + cuerpo + fecha
--   PREGUNTA_FRECUENTE   : titulo = la pregunta, cuerpo = la respuesta
--   ENLACE_INTERES       : titulo = el nombre del sitio, enlace = la URL
--   INFORMACION_CONTACTO : titulo = la etiqueta, cuerpo = el dato
--
-- 'publicada' es obligatoria por los criterios: HU-01 C02 y C03 y RF-034 exigen
-- mostrar "unicamente contenido publicado por la empresa".
--
-- NO se siembra contenido: no corresponde inventar los lineamientos ni el
-- portafolio de una empresa. Con las tablas vacias, la pagina publica responde
-- con el aviso de HU-01 C02, que es el comportamiento correcto.
-- -----------------------------------------------------------------------------
CREATE TABLE contenido_publico (
    id        BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    tipo      VARCHAR(30)   NOT NULL,
    titulo    VARCHAR(250)  NOT NULL,
    cuerpo    VARCHAR(8000),
    enlace    VARCHAR(500),
    fecha     DATE,
    orden     INT,
    publicada BOOLEAN       NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_contenido_publico PRIMARY KEY (id),
    CONSTRAINT ck_contenido_publico_tipo CHECK (tipo IN (
        'LINEAMIENTO',
        'PORTAFOLIO_SERVICIO',
        'NOTICIA',
        'PREGUNTA_FRECUENTE',
        'ENLACE_INTERES',
        'INFORMACION_CONTACTO'))
);

CREATE INDEX ix_contenido_publico_tipo ON contenido_publico (tipo, publicada);

-- -----------------------------------------------------------------------------
-- consulta_publica (RF-035, HU-02)
--
-- HU-02 C05 es la restriccion clave: "mi consulta no aparece en ninguna parte
-- visible para ellas". Por eso no existe ningun endpoint publico que lea esta
-- tabla; solo se escribe desde el formulario.
--
-- PENDIENTE: HU-02 T1 deja abierto que campos de contacto pedira la empresa y
-- cuales seran obligatorios. Solo la pregunta es obligatoria aqui; los datos de
-- contacto quedan opcionales hasta que se definan.
--
-- VACIO DE REQUISITOS: HU-02 T2 deja abierto "quien recibira y atendera las
-- consultas". 'atendida' y 'atendida_por_id' soportan el seguimiento minimo que
-- hace falta para que una consulta recibida no se pierda.
-- -----------------------------------------------------------------------------
CREATE TABLE consulta_publica (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    pregunta          VARCHAR(4000) NOT NULL,   -- CONFIRMADO: RF-035, HU-02 C03
    nombre_contacto   VARCHAR(150),             -- PENDIENTE: obligatoriedad sin definir
    correo_contacto   VARCHAR(150),             -- PENDIENTE; formato validado si se envia (HU-02 C04)
    telefono_contacto VARCHAR(50),              -- PENDIENTE
    recibida_en       TIMESTAMP     NOT NULL,
    atendida          BOOLEAN       NOT NULL DEFAULT FALSE,
    atendida_por_id   BIGINT,

    CONSTRAINT pk_consulta_publica PRIMARY KEY (id),
    CONSTRAINT fk_consulta_atendida_por FOREIGN KEY (atendida_por_id) REFERENCES trabajador (id)
);

CREATE INDEX ix_consulta_publica_atendida ON consulta_publica (atendida, recibida_en);
