-- V15: Gestion, trazabilidad y respuestas a consultas web (RF-035, HU-02)
--
-- Incorpora el ciclo de vida de estados (PENDIENTE, EN_GESTION, RESPONDIDA,
-- ERROR_NOTIFICACION), la fecha de respuesta y la tabla respuesta_consulta
-- para almacenar el historial de respuestas redactadas por el coordinador y
-- el estado de notificacion por correo electronico.
-- =============================================================================

-- Estados e informacion de respuesta en consulta_publica
ALTER TABLE consulta_publica
    ADD COLUMN estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE';

ALTER TABLE consulta_publica
    ADD COLUMN fecha_respuesta TIMESTAMP;

ALTER TABLE consulta_publica
    ADD CONSTRAINT ck_consulta_publica_estado
    CHECK (estado IN ('PENDIENTE', 'EN_GESTION', 'RESPONDIDA', 'ERROR_NOTIFICACION'));

-- Sincronizar registros existentes segun su columna 'atendida'
UPDATE consulta_publica
SET estado = CASE WHEN atendida = TRUE THEN 'RESPONDIDA' ELSE 'PENDIENTE' END;

CREATE INDEX ix_consulta_publica_estado ON consulta_publica (estado, recibida_en);

-- -----------------------------------------------------------------------------
-- respuesta_consulta
--
-- Conserva el historial de respuestas redactadas para cada consulta publica,
-- el trabajador responsable (coordinador), la fecha y el estado de envio
-- de la notificacion por correo. Si el correo falla, el registro se conserva
-- con su detalle de error para permitir reintentos sin perder la redaccion.
-- -----------------------------------------------------------------------------
CREATE TABLE respuesta_consulta (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    consulta_id        BIGINT        NOT NULL,
    trabajador_id      BIGINT        NOT NULL,
    contenido          VARCHAR(4000) NOT NULL,
    fecha_respuesta    TIMESTAMP     NOT NULL,
    enviada_por_correo BOOLEAN       NOT NULL DEFAULT FALSE,
    detalle_error      VARCHAR(1000),

    CONSTRAINT pk_respuesta_consulta PRIMARY KEY (id),
    CONSTRAINT fk_respuesta_consulta_origen FOREIGN KEY (consulta_id) REFERENCES consulta_publica (id) ON DELETE CASCADE,
    CONSTRAINT fk_respuesta_consulta_trabajador FOREIGN KEY (trabajador_id) REFERENCES trabajador (id)
);

CREATE INDEX ix_respuesta_consulta_origen ON respuesta_consulta (consulta_id, fecha_respuesta);

