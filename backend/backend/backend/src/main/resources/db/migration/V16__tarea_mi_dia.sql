-- =============================================================================
-- V16: tareas personales del panel «Mi Dia» (RF-038)
--
-- El panel ya mostraba las actividades que el lider asigna al desarrollador.
-- Esta tabla anade lo que RF-038 no contemplaba pero el checklist necesita: las
-- tareas o recordatorios que el propio trabajador agrega para organizar su dia.
--
-- POR QUE UNA TABLA APARTE Y NO actividad
--
-- Una actividad pertenece a un proyecto y a una etapa, y su ciclo de vida lo
-- gobierna el lider (RF-019 a RF-022). Una tarea personal no tiene proyecto, no
-- la planifica nadie mas y solo existe dentro del panel. Mezclarlas habria
-- obligado a inventar una etapa para cada recordatorio y a relajar las reglas de
-- las actividades.
--
-- El trabajador se toma SIEMPRE de la sesion, nunca del cuerpo de la peticion,
-- de modo que una tarea no puede quedar asociada a otra persona.
-- =============================================================================

CREATE TABLE tarea_mi_dia (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    trabajador_id BIGINT       NOT NULL,
    descripcion   VARCHAR(500) NOT NULL,
    fecha         DATE         NOT NULL,
    completada    BOOLEAN      NOT NULL DEFAULT FALSE,
    creada_en     TIMESTAMP    NOT NULL,

    CONSTRAINT pk_tarea_mi_dia PRIMARY KEY (id),
    CONSTRAINT fk_tarea_mi_dia_trabajador FOREIGN KEY (trabajador_id) REFERENCES trabajador (id)
);

-- La consulta del panel: las tareas de un trabajador para un dia concreto.
CREATE INDEX ix_tarea_mi_dia_trabajador_fecha ON tarea_mi_dia (trabajador_id, fecha);
