-- Selecciones estructuradas de areas y tecnologias por trabajador.
-- Los valores existentes en trabajador.especialidad_desarrollo se conservan
-- sin migrarlos ni interpretarlos como selecciones del nuevo catalogo.
CREATE TABLE trabajador_habilidad (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    trabajador_id  BIGINT       NOT NULL,
    categoria      VARCHAR(20)  NOT NULL,
    nombre         VARCHAR(50)  NOT NULL,

    CONSTRAINT pk_trabajador_habilidad PRIMARY KEY (id),
    CONSTRAINT uk_trabajador_habilidad UNIQUE (trabajador_id, categoria, nombre),
    CONSTRAINT fk_trabajador_habilidad_trabajador FOREIGN KEY (trabajador_id)
        REFERENCES trabajador (id) ON DELETE CASCADE,
    CONSTRAINT ck_trabajador_habilidad_categoria
        CHECK (categoria IN ('AREA', 'LENGUAJE', 'FRAMEWORK', 'BASE_DATOS'))
);

CREATE INDEX ix_trabajador_habilidad_trabajador
    ON trabajador_habilidad (trabajador_id);
