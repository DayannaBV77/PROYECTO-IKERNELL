-- -----------------------------------------------------------------------------
-- proyecto
--
-- Decision C-04: el estado operativo almacenado y el avance calculado son cosas
-- distintas. Aqui solo viven los dos estados que SE ALMACENAN; el avance no es
-- una columna, se calcula al consultarlo.
-- -----------------------------------------------------------------------------
CREATE TABLE proyecto (
    id                   BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    nombre               VARCHAR(150)  NOT NULL,   -- CONFIRMADO: busqueda por nombre (HU-09 C01)
    descripcion          VARCHAR(2000),            -- CONFIRMADO que existe (RF-008); contenido exacto PENDIENTE D-02

    -- CONFIRMADO: habilitado/inhabilitado (RF-015, HU-09 C05). Dominio cerrado.
    estado_habilitacion  VARCHAR(15)   NOT NULL DEFAULT 'HABILITADO',

    -- PENDIENTE D-03: RF-016 habla de "la informacion de estado registrada",
    -- pero los estados posibles los debe definir la empresa. Se deja SIN CHECK
    -- a proposito: anadir la restriccion luego cuesta una linea, mientras que
    -- retirar un dominio equivocado que ya rechazo datos cuesta mucho mas.
    estado_operativo     VARCHAR(30),

    -- PENDIENTE A-02 / D-22: ningun RF declara que el proyecto tenga un lider
    -- responsable, pero HU-10 habla de "su proyecto" y HU-18 de "el lider del
    -- proyecto". Se captura el dato ahora porque es barato; la autorizacion de
    -- nivel 2 que lo usaria NO se aplica hasta que la empresa lo confirme.
    lider_responsable_id BIGINT,

    CONSTRAINT pk_proyecto PRIMARY KEY (id),
    CONSTRAINT ck_proyecto_estado_habilitacion
        CHECK (estado_habilitacion IN ('HABILITADO', 'INHABILITADO')),
    CONSTRAINT fk_proyecto_lider_responsable FOREIGN KEY (lider_responsable_id)
        REFERENCES trabajador (id)
);

-- Criterios de busqueda declarados en RF-013 / HU-09 C01.
CREATE INDEX ix_proyecto_nombre              ON proyecto (nombre);
CREATE INDEX ix_proyecto_estado_habilitacion ON proyecto (estado_habilitacion);

-- -----------------------------------------------------------------------------
-- etapa
--
-- Hija de proyecto: RF-010 exige que la etapa quede asociada a un proyecto
-- existente. La FK no declara ON DELETE CASCADE de forma deliberada, para que
-- la base de datos nunca borre etapas en cascada (RN-02, RNF-003).
-- -----------------------------------------------------------------------------
CREATE TABLE etapa (
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    proyecto_id BIGINT        NOT NULL,            -- CONFIRMADO: RF-010
    nombre      VARCHAR(150)  NOT NULL,            -- CONFIRMADO: RF-010
    descripcion VARCHAR(2000),                     -- CONFIRMADO: RF-010

    -- PROPUESTA: no lo pide ningun RF. Se anticipa porque cualquier calculo de
    -- avance ponderado por etapas lo necesitaria (D-03, HU-12 T1). Nullable
    -- para no obligar a diligenciarlo mientras no se defina.
    orden       INT,

    CONSTRAINT pk_etapa PRIMARY KEY (id),
    CONSTRAINT fk_etapa_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyecto (id),
    -- PROPUESTA: evita dos etapas con el mismo nombre en un proyecto. No esta
    -- en los documentos; se puede retirar si la empresa lo permite.
    CONSTRAINT uk_etapa_proyecto_nombre UNIQUE (proyecto_id, nombre)
);

CREATE INDEX ix_etapa_proyecto ON etapa (proyecto_id);
