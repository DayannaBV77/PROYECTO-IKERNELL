-- -----------------------------------------------------------------------------
-- actividad
--
-- NOTA DE NORMALIZACION: no hay columna proyecto_id. RF-019 exige elegir
-- proyecto, etapa y desarrollador, pero la etapa ya pertenece a un proyecto
-- (V2), asi que guardar el proyecto aqui seria un dato redundante que podria
-- quedar en contradiccion con etapa.proyecto_id. El proyecto se deriva por el
-- join etapa -> proyecto.
-- -----------------------------------------------------------------------------
CREATE TABLE actividad (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    etapa_id         BIGINT        NOT NULL,   -- CONFIRMADO: RF-019, HU-13 C01
    desarrollador_id BIGINT        NOT NULL,   -- CONFIRMADO: RF-019, HU-13 C01
    descripcion      VARCHAR(2000) NOT NULL,   -- CONFIRMADO: RF-019, HU-13 C01

    -- PENDIENTE D-04: RF-022 habla de "los estados y datos definidos por la
    -- empresa", sin enumerarlos. Columna reservada, SIN CHECK y por ahora SIN
    -- ninguna operacion que la escriba: inventar los estados seria definir el
    -- dominio por la empresa. Mismo criterio que proyecto.estado_operativo.
    estado           VARCHAR(20),

    CONSTRAINT pk_actividad PRIMARY KEY (id),
    CONSTRAINT fk_actividad_etapa FOREIGN KEY (etapa_id) REFERENCES etapa (id),
    CONSTRAINT fk_actividad_desarrollador FOREIGN KEY (desarrollador_id) REFERENCES trabajador (id)
);

-- La FK a etapa es la que, junto con el verificador de dependencias, hace
-- efectiva RN-08: una etapa con actividades no se elimina (RF-012, HU-11 C05).
CREATE INDEX ix_actividad_etapa         ON actividad (etapa_id);
CREATE INDEX ix_actividad_desarrollador ON actividad (desarrollador_id);

-- -----------------------------------------------------------------------------
-- ejecucion_actividad
--
-- Decision sobre A-04: RF-022 admite dos lecturas ("iniciar O registrar su
-- ejecucion"). Se eligio tabla propia y no un simple campo de estado en la
-- actividad, porque HU-16 pide "dejando registrado el trabajo que realizo" y
-- porque el reporte de desempeno de HU-07 necesitara ese historial. Un unico
-- campo de estado no guardaria nada de eso.
-- -----------------------------------------------------------------------------
CREATE TABLE ejecucion_actividad (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    actividad_id     BIGINT        NOT NULL,
    ejecutada_por_id BIGINT        NOT NULL,   -- DERIVADO de RN-06
    iniciada_en      TIMESTAMP     NOT NULL,
    finalizada_en    TIMESTAMP,
    observaciones    VARCHAR(2000),            -- PENDIENTE D-04: que datos registra exactamente

    CONSTRAINT pk_ejecucion_actividad PRIMARY KEY (id),
    CONSTRAINT fk_ejecucion_actividad FOREIGN KEY (actividad_id) REFERENCES actividad (id),
    CONSTRAINT fk_ejecucion_trabajador FOREIGN KEY (ejecutada_por_id) REFERENCES trabajador (id)
);

CREATE INDEX ix_ejecucion_actividad ON ejecucion_actividad (actividad_id);
