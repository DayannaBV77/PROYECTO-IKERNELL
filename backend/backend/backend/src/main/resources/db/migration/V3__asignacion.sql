-- =============================================================================
-- Fase 4: asignaciones trabajador-proyecto
--
-- Cubre: RF-003 (el coordinador asigna un trabajador) y RF-009 (el lider asigna
-- desarrolladores a su proyecto).
--
-- Decision S-01: UNA sola tabla para los dos requerimientos. Son la misma
-- relacion trabajador-proyecto; lo que cambia es quien puede crearla y con que
-- rol, y eso se resuelve en la capa de servicio, no duplicando tablas.
-- =============================================================================

CREATE TABLE asignacion (
    id               BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    trabajador_id    BIGINT      NOT NULL,
    proyecto_id      BIGINT      NOT NULL,

    -- DERIVADO de RN-05, Caso de Estudio p.3: "los lideres pueden llegar a ser
    -- desarrolladores de otro proyecto". El tipo global del trabajador no puede
    -- representar eso, porque la misma persona es LIDER en un proyecto y
    -- DESARROLLADOR en otro. De ahi que el rol viva en la asignacion.
    rol_en_proyecto  VARCHAR(15) NOT NULL,

    -- CONFIRMADO que existe: RF-003 habla de "asignacion equivalente activa".
    -- PENDIENTE D-23: ningun requerimiento describe como una asignacion deja de
    -- estar activa, de modo que hoy solo se crean activas.
    activa           BOOLEAN     NOT NULL DEFAULT TRUE,

    -- DERIVADO: hace falta para distinguir las asignaciones creadas por el
    -- coordinador (RF-003) de las creadas por el lider (RF-009), que es
    -- justamente el caso que HU-10 T1 deja abierto.
    asignada_por_id  BIGINT      NOT NULL,

    -- PROPUESTA (D-08): que datos lleva una asignacion sigue sin definirse.
    fecha_asignacion DATE        NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT pk_asignacion PRIMARY KEY (id),
    CONSTRAINT ck_asignacion_rol CHECK (rol_en_proyecto IN ('LIDER', 'DESARROLLADOR')),
    CONSTRAINT fk_asignacion_trabajador FOREIGN KEY (trabajador_id) REFERENCES trabajador (id),
    CONSTRAINT fk_asignacion_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyecto (id),
    CONSTRAINT fk_asignacion_asignada_por FOREIGN KEY (asignada_por_id) REFERENCES trabajador (id)
);

-- IMPORTANTE: NO se declara UNIQUE sobre (trabajador_id, proyecto_id,
-- rol_en_proyecto, activa).
--
-- HU-06 C04 exige una ADVERTENCIA revisable, no un bloqueo: "el sistema me
-- muestra una advertencia [...] para que yo la revise antes de continuar". Una
-- restriccion de base de datos haria imposible que el coordinador decida
-- continuar. La deteccion de duplicados vive en el servicio.
CREATE INDEX ix_asignacion_trabajador ON asignacion (trabajador_id, activa);
CREATE INDEX ix_asignacion_proyecto   ON asignacion (proyecto_id, activa);
