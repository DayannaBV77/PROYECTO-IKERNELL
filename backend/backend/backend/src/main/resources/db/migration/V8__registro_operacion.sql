-- =============================================================================
-- Registro de operaciones (bitacora de auditoria)
--
-- Cubre RNF-003: "el sistema debe conservar la trazabilidad de las operaciones
-- que modifican la informacion". Hasta ahora la unica huella de una operacion
-- era el log de consola, que se pierde al reiniciar.
--
-- QUE SE REGISTRA Y QUE NO
--
-- Se registran las operaciones que ESCRIBEN (POST, PUT, PATCH, DELETE) y
-- cualquier peticion que termine en error. Las consultas de solo lectura NO se
-- registran aqui: son la mayoria del trafico y guardarlas haria crecer la tabla
-- mas rapido que los propios datos del negocio, sin aportar trazabilidad. El
-- SQL de las consultas sigue yendo al log de consola, que es donde se depura.
--
-- POR QUE NO SE GUARDA EL CUERPO DE LA PETICION
--
-- El cuerpo lleva contrasenas en el login y datos personales de los
-- trabajadores en RF-001. Una bitacora no debe convertirse en una segunda copia
-- sin proteger de esos datos. Se guarda el QUE (metodo, ruta, resultado), no el
-- contenido.
-- =============================================================================

CREATE TABLE registro_operacion (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY,

    ocurrida_en      TIMESTAMP     NOT NULL,
    metodo           VARCHAR(10)   NOT NULL,   -- POST, PUT, PATCH, DELETE
    ruta             VARCHAR(500)  NOT NULL,
    codigo_http      INT           NOT NULL,
    exitosa          BOOLEAN       NOT NULL,
    duracion_ms      BIGINT        NOT NULL,

    -- Quien la ejecuto. Nullable porque el login y el formulario publico de
    -- consultas (RF-035) ocurren sin sesion: ahi no hay trabajador que anotar.
    -- NO es una FK a trabajador: si algun dia se depura un trabajador, su
    -- rastro en la bitacora debe sobrevivir, que es justo para lo que sirve.
    trabajador_id    BIGINT,
    correo           VARCHAR(150),

    -- Solo cuando exitosa = FALSE. Guarda el mensaje de negocio ya traducido
    -- (el mismo que vio el cliente), no la traza de la excepcion.
    detalle_error    VARCHAR(2000),

    CONSTRAINT pk_registro_operacion PRIMARY KEY (id)
);

-- Las dos preguntas que se le hacen a una bitacora: "que paso en este rato" y
-- "que fallo". De ahi los dos indices.
CREATE INDEX ix_registro_operacion_fecha  ON registro_operacion (ocurrida_en);
CREATE INDEX ix_registro_operacion_fallos ON registro_operacion (exitosa, ocurrida_en);
