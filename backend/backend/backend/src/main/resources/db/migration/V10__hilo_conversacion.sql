-- -----------------------------------------------------------------------------
-- hilo_conversacion
--
-- El proyecto es obligatorio y la etapa opcional, porque HU-22 contempla las dos
-- formas: C01 habla de "los hilos disponibles para ese proyecto" y C03 de un
-- hilo "asociado a esa etapa". Un hilo con etapa pertenece tambien al proyecto
-- de esa etapa.
--
-- NOTA DE NORMALIZACION: a diferencia de 'actividad' (V4), aqui SI hay columna
-- proyecto_id junto a etapa_id, y no es redundancia: un hilo de proyecto no
-- tiene etapa, de modo que el proyecto no se podria derivar. La coherencia entre
-- las dos columnas -que la etapa, cuando existe, sea de ese proyecto- no cabe en
-- una restriccion de columna y la valida el servicio, igual que en V9.
--
-- VACIO DE REQUISITOS: ningun requerimiento habla de cerrar, archivar ni
-- eliminar un hilo, asi que no hay columna de estado. Anadirla seria inventar
-- una operacion que nadie pidio.
-- -----------------------------------------------------------------------------
CREATE TABLE hilo_conversacion (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    proyecto_id   BIGINT        NOT NULL,   -- CONFIRMADO: RF-037, HU-22 C01
    etapa_id      BIGINT,                   -- CONFIRMADO opcional: HU-22 C03
    titulo        VARCHAR(250)  NOT NULL,   -- CONFIRMADO: RF-037 "datos del hilo"
    creado_por_id BIGINT        NOT NULL,   -- DERIVADO: RF-037 lo crea un trabajador
    creado_en     TIMESTAMP     NOT NULL,

    CONSTRAINT pk_hilo_conversacion PRIMARY KEY (id),
    CONSTRAINT fk_hilo_proyecto   FOREIGN KEY (proyecto_id)   REFERENCES proyecto (id),
    CONSTRAINT fk_hilo_etapa      FOREIGN KEY (etapa_id)      REFERENCES etapa (id),
    CONSTRAINT fk_hilo_creado_por FOREIGN KEY (creado_por_id) REFERENCES trabajador (id)
);

CREATE INDEX ix_hilo_proyecto ON hilo_conversacion (proyecto_id);
CREATE INDEX ix_hilo_etapa    ON hilo_conversacion (etapa_id);

-- -----------------------------------------------------------------------------
-- mensaje_hilo
--
-- HU-22 C02 exige exactamente esto: el mensaje asociado al hilo, con el autor
-- identificado y la fecha de envio.
-- -----------------------------------------------------------------------------
CREATE TABLE mensaje_hilo (
    id         BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    hilo_id    BIGINT         NOT NULL,  -- CONFIRMADO: HU-22 C02
    autor_id   BIGINT         NOT NULL,  -- CONFIRMADO: HU-22 C02 "identificar al autor"
    cuerpo     VARCHAR(4000)  NOT NULL,  -- CONFIRMADO: HU-22 C02 "mensaje valido"
    enviado_en TIMESTAMP      NOT NULL,  -- CONFIRMADO: HU-22 C02 "la fecha de envio"

    CONSTRAINT pk_mensaje_hilo  PRIMARY KEY (id),
    CONSTRAINT fk_mensaje_hilo  FOREIGN KEY (hilo_id)  REFERENCES hilo_conversacion (id),
    CONSTRAINT fk_mensaje_autor FOREIGN KEY (autor_id) REFERENCES trabajador (id)
);

CREATE INDEX ix_mensaje_hilo ON mensaje_hilo (hilo_id, enviado_en);

-- -----------------------------------------------------------------------------
-- lectura_hilo: hasta donde ha leido cada trabajador en cada hilo
--
-- Es lo que hace computable el "no leido". RF-038 exige mostrar al desarrollador
-- "las notificaciones no leidas de los servicios de chat corporativo y correo
-- electronico", y sin guardar la lectura no hay forma de saber que es nuevo.
--
-- Se guarda un INSTANTE y no una marca por mensaje: basta para responder "que
-- hay despues de lo que ya vi" y no crece con el numero de mensajes.
--
-- Clave propia mas UNIQUE sobre el par, en lugar de clave compuesta, para seguir
-- el criterio del resto del esquema (todas las tablas tienen id propio).
-- -----------------------------------------------------------------------------
CREATE TABLE lectura_hilo (
    id             BIGINT    GENERATED BY DEFAULT AS IDENTITY,
    hilo_id        BIGINT    NOT NULL,
    trabajador_id  BIGINT    NOT NULL,
    leido_hasta    TIMESTAMP NOT NULL,

    CONSTRAINT pk_lectura_hilo PRIMARY KEY (id),
    CONSTRAINT uk_lectura_hilo_trabajador UNIQUE (hilo_id, trabajador_id),
    CONSTRAINT fk_lectura_hilo       FOREIGN KEY (hilo_id)       REFERENCES hilo_conversacion (id),
    CONSTRAINT fk_lectura_trabajador FOREIGN KEY (trabajador_id) REFERENCES trabajador (id)
);

CREATE INDEX ix_lectura_trabajador ON lectura_hilo (trabajador_id);
