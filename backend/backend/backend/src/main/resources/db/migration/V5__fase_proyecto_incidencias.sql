-- =============================================================================
-- Fase 6: fases del proyecto, errores e interrupciones
--
-- Cubre: RF-023 (registrar errores) y RF-024 (registrar interrupciones).
--
-- DECISION D-05 RESUELTA: la "fase del proyecto" NO es la "etapa del proyecto".
--   - etapa: pertenece a un proyecto concreto, la registra, modifica y elimina
--     el lider (RF-010 a RF-012) y varia de un proyecto a otro.
--   - fase : es transversal a todos los proyectos; el desarrollador no la
--     registra, solo indica en cual encontro un error o ocurrio una
--     interrupcion (RF-023, RF-024).
--
-- Por eso la fase es un catalogo propio y no una FK a etapa, y por eso ahora si
-- puede declararse NOT NULL, como exige RN-10.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- fase_proyecto: catalogo de referencia, compartido por todos los proyectos.
--
-- No se relaciona con proyecto: la relacion la establece cada incidencia, que
-- apunta a la vez al proyecto y a la fase.
--
-- VALORES PROVISIONALES: ningun documento enumera las fases. Las de abajo son
-- las del ciclo de vida de software que el Caso de Estudio da por supuesto al
-- hablar de "la fase de proyecto en la que se encontro" un error. DEBEN
-- confirmarse con la empresa (decision D-25).
--
-- VACIO DE REQUISITOS: ningun RF define quien administra este catalogo. Se deja
-- solo de lectura; si la empresa necesita mantenerlo, hace falta un RF nuevo.
-- Se usa 'activa' en lugar de borrar, para no romper incidencias historicas.
-- -----------------------------------------------------------------------------
CREATE TABLE fase_proyecto (
    id     BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(80) NOT NULL,
    orden  INT         NOT NULL,
    activa BOOLEAN     NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_fase_proyecto PRIMARY KEY (id),
    CONSTRAINT uk_fase_proyecto_nombre UNIQUE (nombre)
);

