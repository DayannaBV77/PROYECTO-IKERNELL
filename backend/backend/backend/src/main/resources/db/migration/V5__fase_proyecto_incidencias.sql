-- -----------------------------------------------------------------------------
-- error_proyecto (RF-023, HU-17)
--
-- RN-10: el minimo obligatorio es el tipo de error y la fase. La descripcion y
-- la fecha quedan opcionales porque RF-023 dice que el error "podra incluir"
-- esos datos "si la empresa las define como campos obligatorios" (HU-17 C04).
-- -----------------------------------------------------------------------------
CREATE TABLE error_proyecto (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    proyecto_id       BIGINT        NOT NULL,   -- CONFIRMADO: RF-023, HU-17 C03
    tipo_error        VARCHAR(50)   NOT NULL,   -- CONFIRMADO; valores PENDIENTES D-06
    fase_id           BIGINT        NOT NULL,   -- CONFIRMADO: RN-10, ahora que D-05 esta resuelta
    descripcion       VARCHAR(2000),            -- opcional por ahora (HU-17 C04)
    fecha             DATE,                     -- opcional por ahora (HU-17 C04)
    registrado_por_id BIGINT        NOT NULL,   -- DERIVADO: HU-17 restringe quien registra

    CONSTRAINT pk_error_proyecto PRIMARY KEY (id),
    CONSTRAINT fk_error_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyecto (id),
    CONSTRAINT fk_error_fase FOREIGN KEY (fase_id) REFERENCES fase_proyecto (id),
    CONSTRAINT fk_error_registrado_por FOREIGN KEY (registrado_por_id) REFERENCES trabajador (id)
);

CREATE INDEX ix_error_proyecto ON error_proyecto (proyecto_id);

-- -----------------------------------------------------------------------------
-- interrupcion_proyecto (RF-024, HU-18)
--
-- RN-10: los cuatro datos son obligatorios (tipo, fecha, duracion y fase),
-- confirmado por HU-18 C01 y C02.
--
-- La duracion se guarda en valor + unidad porque HU-18 T1 deja abierto "como se
-- registrara la duracion (por ejemplo en horas o en dias)". Guardar la unidad
-- evita tener que migrar datos cuando la empresa decida (D-07).
-- -----------------------------------------------------------------------------
CREATE TABLE interrupcion_proyecto (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    proyecto_id       BIGINT        NOT NULL,   -- CONFIRMADO: RF-024, HU-18 C03
    tipo_interrupcion VARCHAR(50)   NOT NULL,   -- CONFIRMADO; valores PENDIENTES D-07
    fecha             DATE          NOT NULL,   -- CONFIRMADO: RN-10
    duracion_valor    NUMERIC(8, 2) NOT NULL,   -- CONFIRMADO: RN-10
    duracion_unidad   VARCHAR(10)   NOT NULL,   -- unidades del propio HU-18 T1
    fase_id           BIGINT        NOT NULL,   -- CONFIRMADO: RN-10
    registrado_por_id BIGINT        NOT NULL,   -- DERIVADO: HU-18 restringe quien registra

    CONSTRAINT pk_interrupcion_proyecto PRIMARY KEY (id),
    CONSTRAINT ck_interrupcion_unidad CHECK (duracion_unidad IN ('HORAS', 'DIAS')),
    CONSTRAINT ck_interrupcion_duracion CHECK (duracion_valor > 0),
    CONSTRAINT fk_interrupcion_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyecto (id),
    CONSTRAINT fk_interrupcion_fase FOREIGN KEY (fase_id) REFERENCES fase_proyecto (id),
    CONSTRAINT fk_interrupcion_registrado_por FOREIGN KEY (registrado_por_id) REFERENCES trabajador (id)
);

CREATE INDEX ix_interrupcion_proyecto ON interrupcion_proyecto (proyecto_id);
CREATE INDEX ix_interrupcion_fecha    ON interrupcion_proyecto (proyecto_id, fecha);
