-- =============================================================================
-- V17: reportes externos para la empresa brasileña aliada (RF-025, HU-19)
--
-- Esta migracion resuelve las dos piezas que el modulo necesitaba y que el
-- modelo no tenia:
--
--   1. Una marca POR PROYECTO que dice si su informacion puede salir de la
--      empresa. No basta con que el lider tenga el rol: el acuerdo con la
--      empresa brasileña es por proyecto, y un proyecto no autorizado no debe
--      poder exportarse ni pidiendolo por identificador.
--
--   2. Una bitacora propia de cada intento de generacion. La bitacora generica
--      (registro_operacion, V8) anota la peticion HTTP, pero no distingue que
--      proyectos se incluyeron, con que formato se genero ni cuantos registros
--      salieron, que es exactamente lo que un reporte externo debe poder
--      auditar.
--
-- POR QUE LA BITACORA ES UNA TABLA APARTE
--
-- registrar_operacion responde "que peticiones hubo". Esta responde "que salio
-- de la empresa y bajo que condiciones". Son preguntas distintas y mezclarlas
-- habria obligado a llenar de columnas opcionales una tabla que ya usa todo el
-- sistema.
--
-- QUE NO SE GUARDA
--
-- Ni el contenido del archivo ni datos personales de los trabajadores. Solo el
-- identificador del lider, su correo corporativo (ya presente en la bitacora
-- generica) y los identificadores de los proyectos. El archivo en si no se
-- conserva: la auditoria dice que se genero, no se convierte en una segunda
-- copia de los datos.
-- =============================================================================

ALTER TABLE proyecto
    ADD COLUMN reporte_externo_autorizado BOOLEAN NOT NULL DEFAULT FALSE;

-- La consulta del reporte: los proyectos que el acuerdo autoriza, por nombre.
CREATE INDEX ix_proyecto_reporte_externo
    ON proyecto (reporte_externo_autorizado, nombre);

CREATE TABLE auditoria_reporte_externo (
    id                    BIGINT        GENERATED BY DEFAULT AS IDENTITY,

    ocurrida_en           TIMESTAMP     NOT NULL,

    -- Quien genero o intento generar el reporte. Nullable porque una peticion
    -- sin sesion no llega al servicio, pero se deja abierto para no perder el
    -- rastro si algun dia se genera desde un proceso automatico.
    -- NO es FK a trabajador: igual que en registro_operacion, el rastro debe
    -- sobrevivir a una depuracion del trabajador.
    trabajador_id         BIGINT,
    correo                VARCHAR(150),

    -- Proyectos pedidos por el cliente, separados por comas. NULL significa
    -- "todos los autorizados", que es distinto de una lista vacia.
    proyectos_solicitados VARCHAR(2000),

    -- Proyectos que realmente entraron al archivo (los que tenian ejecucion).
    proyectos_incluidos   VARCHAR(2000),

    -- EXITOSO o FALLIDO. Se guarda el intento aunque no haya archivo.
    resultado             VARCHAR(10)   NOT NULL,

    -- Configuracion efectiva con la que se genero. Queda aqui para poder
    -- reconstruir que estructura se entrego aunque la configuracion cambie.
    formato               VARCHAR(20),
    codificacion          VARCHAR(30),
    nombre_archivo        VARCHAR(255),

    total_registros       INT,
    duracion_ms           BIGINT        NOT NULL,

    -- Solo cuando resultado = FALLIDO: el mensaje de negocio que vio el
    -- cliente, no la traza de la excepcion.
    mensaje_error         VARCHAR(2000),

    CONSTRAINT pk_auditoria_reporte_externo PRIMARY KEY (id)
);

-- Las dos preguntas que se le hacen a esta bitacora: "que se genero ultimamente"
-- y "que intentos fallaron".
CREATE INDEX ix_auditoria_reporte_externo_fecha
    ON auditoria_reporte_externo (ocurrida_en);
CREATE INDEX ix_auditoria_reporte_externo_resultado
    ON auditoria_reporte_externo (resultado, ocurrida_en);
